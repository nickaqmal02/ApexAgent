#!/usr/bin/env python3
"""Copies scripts/study_report_template.html into Sources/NotchCore/ReportTemplate.swift as a string.

Why: StudyNotch is installed as a single binary (Homebrew), so it cannot rely on a resource bundle
next to it. The HTML file stays the one source of truth; run this after editing it:
    python3 scripts/embed_report_template.py
NotchCoreTests fails if the two ever differ.
"""
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
html = (ROOT / "scripts" / "study_report_template.html").read_text()
fence = "#####"
assert fence + '"' not in html and '"' + fence not in html, "pick a longer raw-string fence"
out = ROOT / "Sources" / "NotchCore" / "ReportTemplate.swift"
out.write_text(
    "// GENERATED by scripts/embed_report_template.py from scripts/study_report_template.html. Do not edit.\n"
    "enum ReportTemplate {\n"
    f"    static let html: String = {fence}\"\"\"\n{html}\n\"\"\"{fence}\n"
    "}\n")
print(f"wrote {out.relative_to(ROOT)} ({len(html)} characters)")
